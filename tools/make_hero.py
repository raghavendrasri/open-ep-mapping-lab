"""Generate the home page hero: bipolar channels along a decapolar catheter, on recording paper.

Usage:
    python tools/make_hero.py          # write assets/_hero-egm.md
    python tools/make_hero.py --check  # exit 1 if the file is out of date (used by tests)

The traces are computed with the m03 model (labs/python/epml/electrograms.py), using the m03
demo defaults: a planar wave along the catheter at 1 m/s, front width + electrode height
a = 1.3 mm, 2 mm bipoles whose centers are 7 mm apart (the 2-5-2 mm decapolar geometry of
PhysioNet iafdb). Nothing here is hand drawn.
"""

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "labs" / "python"))
from epml.electrograms import bipolar_planar, unipolar  # noqa: E402

OUT = ROOT / "assets" / "_hero-egm.md"

W, H = 760, 268  # SVG viewBox, px
LEFT, RIGHT, TOP, BOTTOM = 78, 16, 14, 30  # plot margins, px
T0, T1 = -12.0, 48.0  # ms shown
C, A_WIDTH, D_BIP, PITCH = 1.0, 1.3, 2.0, 7.0  # m/s, mm, mm, mm
CHANNELS = ["CS1 uni", "CS12", "CS34", "CS56", "CS78", "CS90"]  # distal unipole, then bipoles distal to proximal

INK = "#1e2b37"
MUTED = "#5b6875"
GRID_MINOR = "#f5e3e3"
GRID_MAJOR = "#ebc9c9"


def x_of(t):
    return LEFT + (t - T0) / (T1 - T0) * (W - LEFT - RIGHT)


def path(xs, ys):
    pts = " ".join(f"{x:.1f},{y:.1f}" for x, y in zip(xs, ys))
    return f'<polyline fill="none" stroke="{INK}" stroke-width="1.6" stroke-linejoin="round" points="{pts}"/>'


def build():
    t = np.linspace(T0, T1, 401)
    lane = (H - TOP - BOTTOM) / len(CHANNELS)
    # The wave enters at the distal end (CS12) and travels toward the proximal end. The first
    # channel is the unipolar signal at the distal electrode (CS1), which sits d/2 beyond the
    # CS12 bipole center. As on a recording system, each channel has its own gain.
    unipole = unipolar(-C * t + D_BIP / 2, A_WIDTH)
    bipoles = [bipolar_planar(-C * (t - k * PITCH / C), D_BIP, 0.0, A_WIDTH) for k in range(len(CHANNELS) - 1)]
    traces = [unipole] + bipoles

    parts = [
        f'<svg viewBox="0 0 {W} {H}" role="img" aria-labelledby="hero-title hero-desc" '
        f'xmlns="http://www.w3.org/2000/svg" preserveAspectRatio="xMidYMid meet">',
        '<title id="hero-title">A unipolar and five bipolar electrograms along a decapolar catheter</title>',
        '<desc id="hero-desc">A planar wave travels from the distal pair CS12 to the proximal pair CS90. '
        "The distal unipolar channel shows a positive then negative deflection; each bipole shows a sharp "
        "deflection, 7 milliseconds after its neighbor, on a light grid like recording paper.</desc>",
    ]
    # recording-paper grid: minor every 1 ms, major every 5 ms; horizontal lines at the same pitch
    x_plot0, x_plot1, y0, y1 = LEFT, W - RIGHT, TOP, H - BOTTOM
    px_per_ms = (x_plot1 - x_plot0) / (T1 - T0)
    for ms in np.arange(np.ceil(T0), T1 + 1e-9, 1.0):
        x = x_of(ms)
        color = GRID_MAJOR if int(round(ms)) % 5 == 0 else GRID_MINOR
        parts.append(f'<line x1="{x:.1f}" y1="{y0}" x2="{x:.1f}" y2="{y1}" stroke="{color}" stroke-width="1"/>')
    k = 0
    y = y0
    while y <= y1 + 1e-6:
        color = GRID_MAJOR if k % 5 == 0 else GRID_MINOR
        parts.append(f'<line x1="{x_plot0}" y1="{y:.1f}" x2="{x_plot1}" y2="{y:.1f}" stroke="{color}" stroke-width="1"/>')
        y += px_per_ms
        k += 1

    for i, (name, tr) in enumerate(zip(CHANNELS, traces)):
        baseline = TOP + (i + 0.5) * lane
        scale = 0.42 * lane / np.max(np.abs(tr))
        parts.append(path(x_of(t), baseline - scale * tr))
        parts.append(
            f'<text x="{LEFT - 12}" y="{baseline + 4:.1f}" text-anchor="end" font-size="15" '
            f'font-family="IBM Plex Sans, system-ui, sans-serif" fill="{MUTED}">{name}</text>'
        )

    # time scale bar: 10 ms
    bar_x = x_of(T1 - 12)
    bar_y = H - 10
    parts.append(f'<line x1="{bar_x:.1f}" y1="{bar_y}" x2="{bar_x + 10 * px_per_ms:.1f}" y2="{bar_y}" stroke="{INK}" stroke-width="2"/>')
    parts.append(
        f'<text x="{bar_x + 10 * px_per_ms + 6:.1f}" y="{bar_y + 4}" font-size="12" '
        f'font-family="IBM Plex Sans, system-ui, sans-serif" fill="{MUTED}">10 ms</text>'
    )
    parts.append("</svg>")
    svg = "\n".join(parts)

    caption = (
        "A planar wave passing a decapolar catheter at 1 m/s: the distal unipolar signal, then five 2-mm bipoles "
        "from distal to proximal, each at its own gain. Computed with the model from module m03, not drawn by hand."
    )
    return (
        "<!-- Generated by tools/make_hero.py. Do not edit by hand. -->\n\n"
        "```{=html}\n"
        f'<figure class="hero-egm">\n{svg}\n<figcaption>{caption}</figcaption>\n</figure>\n'
        "```\n"
    )


def main(check=False):
    text = build()
    if check:
        if not OUT.exists() or OUT.read_text() != text:
            print("out of date: assets/_hero-egm.md (run python tools/make_hero.py)")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
