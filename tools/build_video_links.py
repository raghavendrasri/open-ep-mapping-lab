"""Build the "Videos and courses" section of the Useful links page from links/videos.yml.

Usage:
    python tools/build_video_links.py          # write links/_videos.md
    python tools/build_video_links.py --check  # exit 1 if links/_videos.md is out of date (used by tests)

useful-links.qmd includes the generated file with {{< include links/_videos.md >}}. Watch-path totals are summed
here from the item lengths, so no total is typed by hand.
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "links/videos.yml"
OUT = ROOT / "links/_videos.md"

LEVELS = {"intro": "Intro", "intermediate": "Intermediate", "advanced": "Advanced"}
KINDS = {
    "video": "Video",
    "lecture": "Lecture",
    "collection": "Collection",
    "course": "Course",
    "website": "Website",
    "methods": "Methods",
}


def seconds(length):
    """'1:02:03' or '7:50' -> seconds."""
    parts = [int(p) for p in length.split(":")]
    total = 0
    for p in parts:
        total = total * 60 + p
    return total


def hours_minutes(total_seconds):
    minutes = round(total_seconds / 60)
    h, m = divmod(minutes, 60)
    return f"{h} h {m} min" if h else f"{m} min"


def module_pages():
    """Module ID -> (file path, title), from docs/curriculum.md and the files in modules/."""
    titles = dict(re.findall(r"^\| (m\d{2}) \| (.+?) \|$", (ROOT / "docs/curriculum.md").read_text(), re.M))
    pages = {}
    for path in sorted((ROOT / "modules").glob("m[0-9][0-9]-*.qmd")):
        mid = path.name[:3]
        pages[mid] = (f"modules/{path.name}", titles.get(mid, mid))
    return pages


def cell(text):
    """Text safe inside a Markdown pipe table: no pipes, no line breaks, no citation-like @."""
    return str(text).replace("|", "\\|").replace("\n", " ").replace("@", "\\@")


def long_date(iso):
    y, m, d = str(iso).split("-")
    months = "January February March April May June July August September October November December".split()
    return f"{months[int(m) - 1]} {int(d)}, {y}"  # American English (CLAUDE.md §9)


def build(data, pages):
    items = {i["id"]: i for i in data["items"]}
    checked = long_date(data["checked"])
    out = [
        "<!-- Generated by tools/build_video_links.py from links/videos.yml. Edit the YAML, then run the tool. -->",
        "",
        "### Watch paths {#watch-paths}",
        "",
        "Three short sequences to start with, in viewing order. Times are the videos' lengths added up.",
        "",
    ]
    for path in data["paths"]:
        total = sum(seconds(items[i]["length"]) for i in path["items"])
        out.append(f"**{path['title']}** · for {path['for']} · {hours_minutes(total)} in all")
        out.append("")
        for n, iid in enumerate(path["items"], 1):
            it = items[iid]
            out.append(f"{n}. [{cell(it['title'])}]({it['url']}) · {cell(it['source'])} · {it['length']}")
        out.append("")

    # Topics are level-3 headings so each one appears in the page's table of contents.
    out += [
        f"The library below is sorted by topic, most-viewed first within each topic. Views are as YouTube showed them",
        f"on {checked}; ★ marks the course author's own picks. **Read next** links to the course module on the same",
        "subject.",
        "",
    ]
    for key, heading in data["topics"].items():
        rows = [i for i in data["items"] if i["topic"] == key]
        if not rows:
            continue
        rows.sort(key=lambda i: -views_number(i.get("views", "")))
        out += [f"### {heading} {{#videos-{key}}}", ""]
        out.append("| Resource | Source | Length | Views | Read next |")
        out.append("| --- | --- | --- | --- | --- |")
        for it in rows:
            level = f"[{LEVELS[it['level']]}]{{.epml-level .epml-level-{it['level']}}}"
            pick = " [★ Author's pick]{.epml-pick}" if it.get("bookmark") else ""
            why = cell(it["why"])
            if it.get("also"):
                why += f" See also the [{cell(it['also_label'])}]({it['also']})."
            resource = f"[{cell(it['title'])}]({it['url']})<br>{level}{pick} {why}"
            length = it["length"] or KINDS[it["kind"]]
            views = it.get("views") or "–"
            nxt = "–"
            if it.get("next"):
                path, title = pages[it["next"]]
                nxt = f'[{it["next"]}]({path} "{cell(title)}")'
            out.append(f"| {resource} | {cell(it['source'])} | {length} | {views} | {nxt} |")
        out.append("")

    out += ["### Channels worth following {#video-channels}", "", "| Channel | What you will find |", "| --- | --- |"]
    for ch in data["channels"]:
        out.append(f"| [{cell(ch['name'])}]({ch['url']}) | {cell(ch['what'])} |")
    out.append("")
    return "\n".join(out)


def views_number(views):
    """'8.1M' -> 8100000; '' -> -1 (sorts last)."""
    m = re.fullmatch(r"(\d+(?:\.\d+)?)([KM]?)", str(views))
    if not m:
        return -1
    return float(m.group(1)) * {"": 1, "K": 1e3, "M": 1e6}[m.group(2)]


def main():
    data = yaml.safe_load(DATA.read_text())
    text = build(data, module_pages())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("links/_videos.md is out of date: run python tools/build_video_links.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data['items'])} items)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
