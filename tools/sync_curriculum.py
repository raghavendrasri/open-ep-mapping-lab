def number_words(n):
    """Spell out 1-99 for the course-map intro ("Forty-five modules in seven parts")."""
    ones = "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen".split()
    tens = "_ _ twenty thirty forty fifty sixty seventy eighty ninety".split()
    if n < 20:
        return ones[n]
    return tens[n // 10] + ("" if n % 10 == 0 else "-" + ones[n % 10])


def short_name(module_id, title):
    return f"{module_id} · {SHORT_NAMES.get(module_id) or title.split(':', 1)[0].strip()}"


def module_path(module_id):
    return ROOT / "modules" / f"{module_id}-{SLUGS[module_id]}.qmd"


def read_status(path):
    if not path.exists():
        return None
    match = re.match(r"^---\n(.*?)\n---\n", path.read_text(), re.S)
    return (yaml.safe_load(match.group(1)) or {}).get("status") if match else None


def placeholder(module_id, title, part_title, paths):
    topics = split_topics(title)
    in_paths = [name for name, mods in paths if module_id in expand_ids(mods)]
    lines = [
        "---",
        f'title: "{module_id} · {title}"',
        f"module-id: {module_id}",
        f'part: "{part_title}"',
        "# planned | draft | in-review | released",
        "status: planned",
        "clinical-review: pending",
        "---",
        "",
        GENERATED_NOTE,
        "",
        "::: {.callout-note}",
        f"**Planned module.** Not written yet. Planned release: {release_for(module_id, part_title)}.",
        "See the [course map](../course-map.qmd) for every module and its status.",
        ":::",
        "",
    ]
    if topics:
        lines += ["## Planned topics {.unnumbered}", ""] + [f"- {t[0].upper() + t[1:]}" for t in topics] + [""]
    if in_paths:
        lines += ["## Learning paths {.unnumbered}", ""] + [f"- {p}" for p in in_paths] + [""]
    return "\n".join(lines)


def expand_ids(spec):
    """Expand 'm01–m07, m20, m30' into a set of module IDs."""
    ids = set()
    for a, b in re.findall(r"m(\d\d)(?:\s*[–-]\s*m(\d\d))?", spec):
        lo, hi = int(a), int(b or a)
        ids.update(f"m{i:02d}" for i in range(lo, hi + 1))
    return ids


def sidebar(parts):
    contents = [{"href": "course-map.qmd", "text": "Course map"}]
    for part_title, modules in parts:
        contents.append({
            "section": part_title,
            "contents": [
                {"href": f"modules/{m}-{SLUGS[m]}.qmd", "text": short_name(m, t)} for m, t in modules
            ],
        })
    data = {"website": {"sidebar": {"style": "docked", "search": True, "collapse-level": 1, "contents": contents}}}
    header = "# Generated by tools/sync_curriculum.py from docs/curriculum.md. Do not edit by hand.\n"
    return header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=200)


def course_map(parts, paths, statuses):
    n_modules = sum(len(modules) for _, modules in parts)
    lines = [
        "---",
        'title: "Course map"',
        "toc: true",
        "---",
        "",
        GENERATED_NOTE,
        "",
        f"{number_words(n_modules).capitalize()} modules in {number_words(len(parts))} parts. "
        "Each module is built in six stages and reviewed after each one.",
        "Status shows how far each module has got.",
        "",
    ]
    for part_title, modules in parts:
        lines += [f"## {part_title}", "", "| ID | Module | Status | Release |", "| --- | --- | --- | --- |"]
        for m, t in modules:
            key = statuses.get(m) or "planned"
            status = f"[{STATUS_LABELS.get(key, key)}]{{.status .status-{key}}}"
            lines.append(f"| {m} | [{t}](modules/{m}-{SLUGS[m]}.qmd) | {status} | {release_for(m, part_title)} |")
        lines.append("")
    lines += ["## Learning paths", "", "| Path | Modules |", "| --- | --- |"]
    lines += [f"| {name} | {mods} |" for name, mods in paths]
    lines.append("")
    return "\n".join(lines)


def main(check=False):
    parts, paths = parse_curriculum()
    ids = [m for _, modules in parts for m, _ in modules]
    missing = [m for m in ids if m not in SLUGS]
    if missing:
        sys.exit(f"Add slugs to SLUGS in tools/sync_curriculum.py for: {missing}")

    outputs = {}
    statuses = {}
    for part_title, modules in parts:
        for m, t in modules:
            path = module_path(m)
            status = read_status(path)
            if status in (None, "planned"):
                outputs[path] = placeholder(m, t, part_title, paths)
                status = "planned"
            statuses[m] = status
    outputs[ROOT / "_sidebar.yml"] = sidebar(parts)
    outputs[ROOT / "course-map.qmd"] = course_map(parts, paths, statuses)

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p in stale:
        p.write_text(outputs[p])
        print(f"wrote {p.relative_to(ROOT)}")
    print(f"{len(ids)} modules, {sum(s == 'planned' for s in statuses.values())} planned, {len(stale)} files updated.")
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
