def parse_curriculum():
    """Return (parts, paths): parts = [(part_title, [(id, title), ...])], paths = [(path, modules)]."""
    text = (ROOT / "docs" / "curriculum.md").read_text()
    parts, paths, section = [], [], None
    for line in text.splitlines():
        heading = re.match(r"^## (.+)$", line)
        if heading:
            section = heading.group(1).strip()
            if section.startswith("Part "):
                parts.append((section, []))
            continue
        row = re.match(r"^\| (m\d\d) \| (.+?) \|$", line)
        if row and section and section.startswith("Part "):
            parts[-1][1].append((row.group(1), row.group(2).strip()))
            continue
        path_row = re.match(r"^\| ([^|]+?) \| ([^|]+?) \|$", line)
        if section == "Learning paths" and path_row and path_row.group(1) not in ("Path", "---"):
            paths.append((path_row.group(1).strip(), path_row.group(2).strip()))
    return parts, paths


def release_for(module_id, part_title):
    if module_id == "m03":
        return "Pilot"
    if module_id in V01:
        return "v0.1"
    part = part_title.split(" ·")[0]
    if module_id in V05_EXTRA or part in V05_PARTS:
        return "v0.5"
    if part in V15_PARTS:
        return "v1.5"
    if part in UNSCHEDULED_PARTS:
        return "not yet scheduled"
    return "v1.0"


def split_topics(title):
    """Topics after the colon, split on top-level commas (commas inside parentheses are kept)."""
    if ":" not in title:
        return []
    rest = title.split(":", 1)[1].strip()
    items, depth, current = [], 0, ""
    for ch in rest:
        depth += ch == "("
        depth -= ch == ")"
        if ch == "," and depth == 0:
            items.append(current.strip())
            current = ""
        else:
            current += ch
    items.append(current.strip())
    if items[-1].startswith("and "):
        items[-1] = items[-1][4:]
    return [i for i in items if i]


