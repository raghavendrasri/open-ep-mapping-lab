"""Checks that course content follows the rules in CLAUDE.md.

Runs on every pull request. Each failure message says which rule was broken and where.
"""

import json
import re
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
MODULE_FILES = sorted((ROOT / "modules").glob("m[0-9][0-9]-*.qmd"))
TEMPLATE = ROOT / "templates" / "module-template.qmd"

# CLAUDE.md §3: level-2 headings every module has, in this order.
REQUIRED_HEADINGS = [
    "In 60 seconds",
    "From the field",
    "Derivations",
    "Clinical correlate",
    "Visual summary",
    "How experts think",
    "Cheat sheet",
    "Interview questions",
    "Code lab",
    "Self-check",
    "Literature figures",
    "Further reading",
]

# CLAUDE.md §4
ALLOWED_BADGES = {"exact", "simulation", "approximate model", "schematic"}
STATUSES = {"planned", "draft", "in-review", "released"}
CLINICAL_REVIEW = {"pending", "signed-off"}

# CLAUDE.md §5: markers that must not appear in released modules.
UNFINISHED_MARKERS = ["TODO(source)", "[unverified]"]


def split_front_matter(text):
    match = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    assert match, "file must start with YAML front matter between --- lines"
    return yaml.safe_load(match.group(1)), match.group(2)


def h2_headings(body):
    return [m.group(1).strip() for m in re.finditer(r"^## (.+)$", body, re.M)]


def curriculum_ids():
    text = (ROOT / "docs" / "curriculum.md").read_text()
    return set(re.findall(r"^\| (m\d\d) \|", text, re.M))


def demo_divs(body):
    """Return (attributes, content) for every `.demo` fenced div, including nested ones."""
    demos, stack = [], []
    for line in body.splitlines():
        fence = re.match(r"^(:{3,})\s*(.*)$", line)
        if fence and fence.group(2):  # opening fence, with attributes
            stack.append({"attrs": fence.group(2), "lines": []})
        elif fence:  # closing fence
            if stack:
                div = stack.pop()
                if ".demo" in div["attrs"]:
                    demos.append((div["attrs"], "\n".join(div["lines"])))
                if stack:  # keep nested divs, fence included, in the parent's content
                    stack[-1]["lines"].extend([f":::{{{div['attrs']}}}" if not div["attrs"].startswith("{") else f"::: {div['attrs']}"] + div["lines"])
        elif stack:
            stack[-1]["lines"].append(line)
    return demos


def module_ids(path):
    return pytest.param(path, id=path.stem)


def test_at_least_one_module_exists():
    assert MODULE_FILES, "no modules found in modules/"


@pytest.mark.parametrize("path", [module_ids(p) for p in MODULE_FILES] + [pytest.param(TEMPLATE, id="template")])
def test_required_sections_in_order(path):
    meta, body = split_front_matter(path.read_text())
    if meta.get("status") == "planned":
        pytest.skip("planned placeholder pages are generated by tools/sync_curriculum.py")
    headings = h2_headings(body)
    assert headings == REQUIRED_HEADINGS, (
        f"{path.name}: level-2 headings must be exactly, in order:\n  {REQUIRED_HEADINGS}\n"
        f"found:\n  {headings}"
    )


@pytest.mark.parametrize("path", [module_ids(p) for p in MODULE_FILES])
def test_front_matter(path):
    meta, _ = split_front_matter(path.read_text())
    module_id = path.name[:3]
    assert meta.get("module-id") == module_id, f"{path.name}: module-id must be {module_id}"
    assert module_id in curriculum_ids(), f"{path.name}: {module_id} is not in docs/curriculum.md"
    assert str(meta.get("title", "")).startswith(f"{module_id} · "), (
        f"{path.name}: title must start with '{module_id} · '"
    )
    assert meta.get("part"), f"{path.name}: front matter needs a 'part'"
    assert meta.get("status") in STATUSES, f"{path.name}: status must be one of {sorted(STATUSES)}"
    assert meta.get("clinical-review") in CLINICAL_REVIEW, (
        f"{path.name}: clinical-review must be one of {sorted(CLINICAL_REVIEW)}"
    )


@pytest.mark.parametrize("path", [module_ids(p) for p in MODULE_FILES] + [pytest.param(TEMPLATE, id="template")])
def test_demos_have_badge_and_assumptions(path):
    _, body = split_front_matter(path.read_text())
    for attrs, content in demo_divs(body):
        badge = re.search(r'badge="([^"]*)"', attrs)
        assert badge and badge.group(1) in ALLOWED_BADGES, (
            f"{path.name}: demo {{{attrs}}} needs badge= one of {sorted(ALLOWED_BADGES)}"
        )
        assert re.search(r"^\*\*Assumptions\*\*", content, re.M), (
            f"{path.name}: demo {{{attrs}}} needs an **Assumptions** list"
        )
        # An interactive demo has an ID like #m03-d1; a static figure box holds a numbered
        # Quarto figure with an ID like #fig-m03-filter-chain (CLAUDE.md §9).
        has_id = re.search(r"#m\d\d-d\d+", attrs) or "#mNN-d" in attrs or re.search(r"\{#fig-m\d\d-[a-z0-9-]+", content)
        assert has_id, f"{path.name}: demo {{{attrs}}} needs an ID like #m03-d1 or a nested figure #fig-m03-..."
        assert len(re.findall(r"^\*\*Assumptions\*\*", content, re.M)) == 1, (
            f"{path.name}: demo {{{attrs}}} needs exactly one **Assumptions** list"
        )


@pytest.mark.parametrize("path", [module_ids(p) for p in MODULE_FILES])
def test_released_modules_are_finished(path):
    meta, body = split_front_matter(path.read_text())
    if meta.get("status") != "released":
        pytest.skip("only released modules are checked for unfinished work")
    for marker in UNFINISHED_MARKERS:
        assert marker not in body, f"{path.name}: released module still contains {marker}"
    assert meta.get("clinical-review") == "signed-off", (
        f"{path.name}: released module needs clinical-review: signed-off (set by a human)"
    )
    assert "**Key takeaways**" in body, f"{path.name}: released module needs Key takeaways"


def section(body, heading):
    """Text of one level-2 section, up to the next level-2 heading."""
    match = re.search(rf"^## {re.escape(heading)}\n(.*?)(?=^## |\Z)", body, re.M | re.S)
    return match.group(1) if match else ""


# CLAUDE.md §3 and §11: question sections, their numbering, answer label and released minimum.
QUESTION_SECTIONS = {
    "Interview questions": ("Q", "Model answer", 10),
    "Self-check": ("S", "Answer", 5),
}


@pytest.mark.parametrize("heading", list(QUESTION_SECTIONS))
@pytest.mark.parametrize("path", [module_ids(p) for p in MODULE_FILES])
def test_questions_have_answers(path, heading):
    """Questions are numbered **Q1.**, **Q2.**, ... (interview) or **S1.**, ... (self-check), and each
    is followed by exactly one answer in a <details class="model-answer"> block. Released modules
    need at least 10 interview and 5 self-check questions (CLAUDE.md §11)."""
    meta, body = split_front_matter(path.read_text())
    if meta.get("status") == "planned":
        pytest.skip("planned placeholder pages have no questions")
    prefix, label, minimum = QUESTION_SECTIONS[heading]
    answer = f'<details class="model-answer">\n<summary>{label}</summary>'
    text = section(body, heading)
    numbers = [int(n) for n in re.findall(rf"^\*\*{prefix}(\d+)\. ", text, re.M)]
    assert numbers == list(range(1, len(numbers) + 1)), f"{path.name}: {heading} must be numbered {prefix}1, {prefix}2, ..."
    blocks = re.split(rf"^\*\*{prefix}\d+\. ", text, flags=re.M)[1:]
    for n, block in zip(numbers, blocks):
        assert block.count(answer) == 1, f"{path.name}: {prefix}{n} needs exactly one '{label}' block"
        assert "</details>" in block, f"{path.name}: {prefix}{n}'s answer is not closed with </details>"
    if meta.get("status") == "released":
        assert len(numbers) >= minimum, f"{path.name}: released module needs at least {minimum} {heading.lower()}"


@pytest.mark.parametrize("path", [module_ids(p) for p in MODULE_FILES])
def test_every_equation_has_a_test(path):
    """CLAUDE.md §5: every numbered equation is named in at least one test in tests/."""
    labels = re.findall(r"\{#(eq-[a-z0-9-]+)\}", path.read_text())
    test_text = "\n".join(p.read_text() for p in (ROOT / "tests").glob("test_*.py"))
    missing = [label for label in labels if not re.search(re.escape(label) + r"(?![a-z0-9-])", test_text)]
    assert not missing, f"{path.name}: equations without a test naming them: {missing}"


def test_citations_are_in_references_bib():
    """CLAUDE.md §5: every [@key] cited in a module exists in references.bib."""
    keys = set(re.findall(r"^@\w+\{([^,]+),", (ROOT / "references.bib").read_text(), re.M))
    for path in MODULE_FILES:
        cited = set(re.findall(r"@([A-Za-z][A-Za-z0-9_]*)", re.sub(r"@eq-[a-z0-9-]+", "", path.read_text())))
        missing = sorted(cited - keys)
        assert not missing, f"{path.name}: cites keys missing from references.bib: {missing}"


def test_references_have_doi_or_pmid():
    text = (ROOT / "references.bib").read_text()
    entries = re.split(r"\n(?=@)", text)
    for entry in entries:
        if not entry.strip().startswith("@"):
            continue
        key = re.match(r"@\w+\{([^,]+),", entry.strip())
        assert re.search(r"^\s*(doi|pmid)\s*=", entry, re.M | re.I), (
            f"references.bib: entry {key.group(1) if key else '?'} needs a doi or pmid field"
        )


